const path = require('path');
const fs = require('fs');

// Generate a simple 1x1 PNG buffer
const createDummyImageBuffer = () => {
  return Buffer.from([
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
    0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
    0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53,
    0xDE, 0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41,
    0x54, 0x08, 0xD7, 0x63, 0xF8, 0x0F, 0x04, 0x00,
    0x03, 0x58, 0x01, 0x03, 0x50, 0xDE, 0xAB, 0x3F,
    0x49, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E,
    0x44, 0xAE, 0x42, 0x60, 0x82
  ]);
};

// Create a temporary file path for attaching
const createTempImageFile = (filename = 'test-image.png') => {
  const tmpDir = path.join(__dirname, 'tmp');
  if (!fs.existsSync(tmpDir)) fs.mkdirSync(tmpDir, { recursive: true });
  const filePath = path.join(tmpDir, filename);
  fs.writeFileSync(filePath, createDummyImageBuffer());
  return filePath;
};

// Clean up temp files
const cleanupTempFiles = () => {
  const tmpDir = path.join(__dirname, 'tmp');
  if (fs.existsSync(tmpDir)) {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
};

module.exports = { createDummyImageBuffer, createTempImageFile, cleanupTempFiles };
